import re

def cyrillic_to_latin(text: str) -> str:
    # Словарь соответствия русских букв английским
    rules = {
        'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo',
        'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
        'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
        'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch',
        'ы': 'y', 'э': 'e', 'ю': 'yu', 'я': 'ya',
        # Дополнительно переводим пробелы и дефисы
        ' ': '-', '_': '-'
    }
    
    # Переводим текст в нижний регистр для упрощения
    text = text.lower().strip()
    
    # Посимвольно заменяем русские буквы на английские
    output = []
    for char in text:
        output.append(rules.get(char, char))  # Если символа нет в словаре, оставляем как есть
        
    result = "".join(output)
    
    # Удаляем любые символы, которые НЕ являются буквами, цифрами или дефисом
    result = re.sub(r'[^a-z0-9-]', '', result)
    
    # Убираем двойные дефисы, если они случайно образовались (например, "--")
    result = re.sub(r'-+', '-', result)
    
    return result.strip('-')
